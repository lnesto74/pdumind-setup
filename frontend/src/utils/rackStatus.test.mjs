import assert from 'node:assert/strict';
import {aggregateRackStatus,readPowerEvidence,matchesRackFilter,rackStatusCounts,mergeCommunicationEvidence} from './rackStatus.js';
const now=Date.parse('2026-10-14T01:00:00Z');
const pdu=(slot)=>({id:slot,dbId:slot,ip:slot,position:slot,hostname:`Actual PDU ${slot}`});
const rack={id:'E01',pdus:[pdu('A'),pdu('B')]};
const ev=(state,extra={})=>({telemetry:{power_state:state,measured_at:now,alarms:[],...extra},communication:{state:'online',receivedAt:now}});
const status=e=>aggregateRackStatus(rack,e,now);
assert.equal(aggregateRackStatus({pdus:[]},{},now).state,'no_pdu');
assert.equal(status({}).state,'unknown');
assert.equal(status({A:ev('on'),B:ev('on')}).state,'on');
assert.equal(status({A:ev('off'),B:ev('off')}).state,'off');
assert.equal(status({A:ev('on'),B:ev('off')}).state,'partial');
assert.equal(status({A:ev('on')}).state,'unknown');
assert.equal(status({A:ev('on',{TotalCurrent:0}),B:ev('on',{TotalCurrent:0})}).state,'on');
assert.equal(readPowerEvidence({results:[{name:'TotalCurrent',value:'0'},{name:'Output1Status',value:'Off'}]}).state,'unknown');
assert.equal(status({A:ev('on',{measured_at:now-91000}),B:ev('on')}).state,'unknown');
assert.equal(status({A:ev('on',{measured_at:null}),B:ev('on')}).state,'unknown');
const disconnected={...ev('off'),communication:{state:'offline',receivedAt:now}};
assert.equal(status({A:disconnected,B:ev('off')}).state,'unknown');
assert.equal(status({A:disconnected,B:ev('off')}).disconnected,true);
const warning={severity:'warning',active:true,timestamp:now,message:'Load warning'};
const critical={severity:'critical',active:true,timestamp:now,message:'Input alarm'};
assert.equal(status({A:ev('on',{alarms:[warning]}),B:ev('off')}).state,'warning');
let both=status({A:ev('on',{alarms:[warning,critical]}),B:disconnected});
assert.equal(both.state,'critical');assert.equal(both.disconnected,true);assert.equal(both.activeAlarms.length,2);
assert.equal(status({A:ev('on',{alarms:[{...critical,active:false}]}),B:ev('on')}).state,'on');
const stale=status({A:ev('on',{alarms:[{...critical,timestamp:now-91000}]}),B:ev('on')});
assert.equal(stale.state,'on');assert.equal(stale.lastKnownAlarms.length,1);assert.equal(stale.lastKnownAlarms[0].timestamp,now-91000);
assert(matchesRackFilter(stale,'issues'));assert(!matchesRackFilter(stale,'critical'));
const three=aggregateRackStatus({pdus:[pdu('A'),pdu('B'),pdu('C')]},{A:ev('off'),B:ev('on'),C:ev('on')},now);assert.equal(three.state,'partial');assert.equal(three.devices.length,3);
assert.equal(aggregateRackStatus(rack,{A:ev('on'),B:ev('on')},now+91000).state,'unknown');
assert.equal(status({A:{...ev('on'),telemetryUnavailable:true},B:ev('on')}).state,'unknown');
const counts=rackStatusCounts({first:both,second:three,third:aggregateRackStatus({pdus:[]},{},now)});assert.equal(counts.all,3);assert.equal(counts.issues,1);assert.equal(counts.partial,1);assert.equal(counts.no_pdu,1);
console.log('PASS: assignment, zero-load energised, on/off/mixed, incomplete/stale power, communication loss, simultaneous/cleared/stale alarms, timestamps, 3+ PDUs and filters.');

const priorLoss={state:'offline',receivedAt:now-100000,timestamp:now-100000};
const failedPoll=mergeCommunicationEvidence(priorLoss);
assert.equal(failedPoll.state,'offline');assert.equal(failedPoll.receivedAt,priorLoss.receivedAt);
const retained=status({A:{...ev('on'),communication:failedPoll},B:ev('on')});
assert.equal(retained.disconnected,true);assert.equal(retained.state,'unknown');
assert.equal(mergeCommunicationEvidence({state:'online',receivedAt:now}).state,'unknown');
const recovery=mergeCommunicationEvidence(failedPoll,{state:'online',receivedAt:now});
assert.equal(status({A:{...ev('on'),communication:recovery},B:ev('on')}).disconnected,false);
console.log('PASS: failed reachability polls preserve prior disconnection; only verified recovery clears it.');
